'use client';

import { useEffect, useState } from 'react';
import { ShieldCheck } from '@phosphor-icons/react';
import { Button } from '@/components/ui/Button';
import { Input } from '@/components/ui/Input';
import { useSession } from '@/lib/session';

type State =
  | { step: 'loading' }
  | { step: 'enroll'; factorId: string; qr: string; secret: string }
  | { step: 'verify'; factorId: string }
  | { step: 'done' }
  | { step: 'error'; message: string };

/**
 * Two-step sign-in with an authenticator app (TOTP). Sets it up when there is none, otherwise asks
 * for a code to raise this session to two-step level (AAL2).
 */
export function TwoStep({ onDone }: { onDone: () => void }) {
  const { client } = useSession();
  const [state, setState] = useState<State>({ step: 'loading' });
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    (async () => {
      const { data, error: e } = await client.auth.mfa.listFactors();
      if (e) return active && setState({ step: 'error', message: 'Could not load two-step settings.' });
      const verified = data.totp.find((f) => f.status === 'verified');
      if (verified) return active && setState({ step: 'verify', factorId: verified.id });
      // Clear half-finished set-ups, then start a new one.
      for (const f of data.all.filter((x) => x.status === 'unverified')) {
        await client.auth.mfa.unenroll({ factorId: f.id });
      }
      const en = await client.auth.mfa.enroll({ factorType: 'totp', friendlyName: `Authenticator ${Date.now()}` });
      if (en.error || !en.data) return active && setState({ step: 'error', message: 'Could not start two-step set-up.' });
      if (active) setState({ step: 'enroll', factorId: en.data.id, qr: en.data.totp.qr_code, secret: en.data.totp.secret });
    })();
    return () => {
      active = false;
    };
  }, [client]);

  const verify = async () => {
    if (state.step !== 'enroll' && state.step !== 'verify') return;
    setError(null);
    if (!/^\d{6}$/.test(code)) return setError('Enter the 6-digit code from your app.');
    setBusy(true);
    const { error: e } = await client.auth.mfa.challengeAndVerify({ factorId: state.factorId, code });
    setBusy(false);
    if (e) return setError('That code did not work. Check the time on your phone and try the newest code.');
    setState({ step: 'done' });
    onDone();
  };

  if (state.step === 'loading') return <p className="text-sm text-muted">Loading</p>;
  if (state.step === 'error') return <p className="text-sm text-danger">{state.message}</p>;
  if (state.step === 'done') {
    return (
      <p className="flex items-center gap-2 text-sm font-semibold">
        <ShieldCheck size={18} aria-hidden /> Two-step sign-in is on for this session.
      </p>
    );
  }

  return (
    <div className="flex flex-col gap-4">
      {state.step === 'enroll' ? (
        <>
          <p className="text-[15px]">
            Scan this code with an authenticator app (Google Authenticator, Microsoft Authenticator or 1Password),
            then enter the 6-digit code it shows.
          </p>
          {/* The QR code is an SVG data URL generated by the auth server. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={state.qr} alt="QR code for your authenticator app" className="size-48 rounded-box bg-white p-2" />
          <p className="text-sm text-muted">
            Cannot scan? Enter this key: <span className="font-mono break-all text-fg" data-testid="totp-secret">{state.secret}</span>
          </p>
        </>
      ) : (
        <p className="text-[15px]">Enter the 6-digit code from your authenticator app.</p>
      )}
      <Input
        label="Code"
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={6}
        value={code}
        onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
        error={error ?? undefined}
      />
      <Button onClick={verify} loading={busy} className="self-start">
        {state.step === 'enroll' ? 'Turn on two-step sign-in' : 'Verify'}
      </Button>
    </div>
  );
}
